//! Command-line interface arguments for `alhalte-banquette`.

use std::path::PathBuf;

use clap::Parser;

use crate::secret_file::{SecretFileError, resolve_secret};

/// Command-line arguments for the `alhalte-banquette` room daemon.
#[derive(Parser, Debug, Clone)]
#[command(
    name = "alhalte-banquette",
    about = "Session room process managing scenes, logs, and state relay for Alhalte",
    version
)]
pub struct CliArgs {
    /// 64-bit room identifier (16 hex characters or legacy decimal).
    #[arg(long, env = "ALHALTE_ROOM_ID", value_parser = parse_room_id_arg)]
    pub room_id: u64,

    /// Initial room administrator account ID.
    #[arg(long, alias = "owner", env = "ALHALTE_ADMIN_ACCOUNT")]
    pub admin: u64,

    /// UNIX domain socket path for communication with `alhalte-maitre-d` (Unix).
    #[arg(
        long,
        default_value = "/tmp/alhalte-banquette.sock",
        env = "ALHALTE_SOCKET_PATH"
    )]
    pub socket: PathBuf,

    /// Windows named-pipe path for communication with `alhalte-maitre-d`.
    ///
    /// Required on Windows (for example `\\.\pipe\alhalte-banquette-...`);
    /// ignored on Unix.
    #[arg(long, env = "ALHALTE_PIPE_NAME")]
    pub pipe_name: Option<String>,

    /// Base HTTP URL of the `alhalte-cellar` content storage service.
    ///
    /// Cellar is also the source of the room head: startup reads the
    /// `room/<room-id>/head` alias and restores the room when it is set
    /// (Issue #192), so no restore flag exists.
    #[arg(
        long,
        default_value = "http://127.0.0.1:8080",
        env = "ALHALTE_CELLAR_URL"
    )]
    pub cellar_url: String,

    /// Log chunk size exponent $N$. One chunk holds $1 \ll N$ entries (default 8 = 256 entries).
    #[arg(
        short = 'n',
        long,
        default_value = "8",
        env = "ALHALTE_CHUNK_SIZE_EXPONENT"
    )]
    pub chunk_size_exponent: u8,

    /// Periodic heartbeat interval in seconds (default 240 seconds = 4 minutes).
    #[arg(long, default_value = "240", env = "ALHALTE_HEARTBEAT_INTERVAL_SECS")]
    pub heartbeat_interval_secs: u64,

    /// Internal cellar service token used for room state persistence.
    ///
    /// Sent as `X-Alhalte-Service-Token` so internal writes do not impersonate a
    /// user session. Room head alias updates require the same token. The value
    /// is never logged.
    ///
    /// Prefer `--service-token-file`: an inline value is visible in `ps`.
    #[arg(long, env = "ALHALTE_SERVICE_TOKEN", hide_env_values = true)]
    pub service_token: Option<String>,

    /// File containing the internal cellar service token (mode 0600).
    ///
    /// `alhalte-maitre-d` forwards the file path it received, so the token never
    /// appears in `ps` or in a systemd unit (Issue #194). Takes precedence over
    /// `--service-token`.
    #[arg(long, env = "ALHALTE_SERVICE_TOKEN_FILE")]
    pub service_token_file: Option<PathBuf>,
}

impl CliArgs {
    /// Resolves the internal service token from the file or the inline value.
    ///
    /// # Errors
    ///
    /// Returns [`SecretFileError`] when the file is not owner-only, empty, or
    /// unreadable.
    pub fn resolve_service_token(&self) -> Result<Option<String>, SecretFileError> {
        resolve_secret(
            self.service_token_file.as_deref(),
            self.service_token.as_deref(),
        )
    }
}

/// Parses a room ID argument in canonical 16-hex or legacy decimal form.
///
/// A 16-character all-digit string is interpreted as hex, matching the
/// canonical room ID form generated by the client.
fn parse_room_id_arg(value: &str) -> Result<u64, String> {
    let value = value.trim();
    if value.is_empty() {
        return Err("room ID must not be empty".to_string());
    }

    if value.len() == 16 && value.bytes().all(|byte| byte.is_ascii_hexdigit()) {
        return u64::from_str_radix(value, 16)
            .map_err(|_| "room ID is not a valid 16-hex value".to_string());
    }

    if value.bytes().all(|byte| byte.is_ascii_digit()) {
        return value
            .parse::<u64>()
            .map_err(|_| "room ID is not a valid decimal 64-bit unsigned integer".to_string());
    }

    Err(
        "room ID must be 16 hexadecimal characters or a decimal 64-bit unsigned integer"
            .to_string(),
    )
}

/// Parses CLI arguments from `std::env::args_os()`.
pub fn parse_cli_args() -> CliArgs {
    CliArgs::parse()
}

#[cfg(test)]
mod tests {
    use super::*;

    // spec: alhalte-banquette/cli --room-id canonical 16 hex + legacy decimal
    #[test]
    fn accepts_hex_and_decimal_room_ids() {
        let hex = CliArgs::try_parse_from([
            "alhalte-banquette",
            "--room-id",
            "abcdef0123456789",
            "--admin",
            "1",
        ])
        .unwrap();
        assert_eq!(hex.room_id, 0xabcdef0123456789);

        let decimal =
            CliArgs::try_parse_from(["alhalte-banquette", "--room-id", "777", "--admin", "1"])
                .unwrap();
        assert_eq!(decimal.room_id, 777);

        let padded = CliArgs::try_parse_from([
            "alhalte-banquette",
            "--room-id",
            "0000000000000309",
            "--admin",
            "1",
        ])
        .unwrap();
        assert_eq!(padded.room_id, 0x309);
    }

    #[test]
    fn rejects_arbitrary_room_ids() {
        assert!(
            CliArgs::try_parse_from(["alhalte-banquette", "--room-id", "room-1", "--admin", "1",])
                .is_err()
        );
        assert!(parse_room_id_arg("0x1234").is_err());
        assert!(parse_room_id_arg("18446744073709551616").is_err());
    }

    // spec: alhalte-banquette/transport 0002 --pipe-name selects the Windows transport
    #[test]
    fn parses_named_pipe_transport() {
        let args = CliArgs::try_parse_from([
            "alhalte-banquette",
            "--room-id",
            "777",
            "--admin",
            "1",
            "--pipe-name",
            r"\\.\pipe\alhalte-banquette-test",
        ])
        .unwrap();
        assert_eq!(
            args.pipe_name.as_deref(),
            Some(r"\\.\pipe\alhalte-banquette-test")
        );

        let args =
            CliArgs::try_parse_from(["alhalte-banquette", "--room-id", "777", "--admin", "1"])
                .unwrap();
        assert_eq!(args.pipe_name, None);
    }

    // spec: alhalte-banquette/persistence 0007 the room head comes from cellar, not argv
    #[test]
    fn rejects_the_removed_room_tin_flag() {
        // The head is read from the `room/<room-id>/head` cellar alias, so the
        // former restore argument is gone instead of being silently ignored.
        assert!(
            CliArgs::try_parse_from([
                "alhalte-banquette",
                "--room-id",
                "777",
                "--admin",
                "1",
                "--room-tin",
                &"ab".repeat(32),
            ])
            .is_err()
        );

        // No restore flag and no service token by default.
        let args =
            CliArgs::try_parse_from(["alhalte-banquette", "--room-id", "777", "--admin", "1"])
                .unwrap();
        assert_eq!(args.service_token, None);

        // The inline token is still parsed (the 0600 file wins when both exist).
        let args = CliArgs::try_parse_from([
            "alhalte-banquette",
            "--room-id",
            "777",
            "--admin",
            "1",
            "--service-token",
            "internal-secret",
        ])
        .unwrap();
        assert_eq!(args.service_token.as_deref(), Some("internal-secret"));
    }
}

#[cfg(test)]
mod secret_file_tests {
    use super::*;
    use std::io::Write;
    use std::os::unix::fs::{OpenOptionsExt, PermissionsExt};

    // spec: alhalte-banquette/cli 0007 the token is read from a 0600 file and the
    // file wins over an inline value
    #[test]
    fn resolves_service_token_from_file() {
        let dir = tempfile::tempdir().unwrap();
        let path = dir.path().join("service-token");
        let mut file = std::fs::OpenOptions::new()
            .write(true)
            .create(true)
            .truncate(true)
            .mode(0o600)
            .open(&path)
            .unwrap();
        file.write_all(b"file-token\n").unwrap();
        drop(file);

        let args = CliArgs::try_parse_from([
            "alhalte-banquette",
            "--room-id",
            "777",
            "--admin",
            "1",
            "--service-token",
            "inline-token",
            "--service-token-file",
            path.to_str().unwrap(),
        ])
        .unwrap();
        assert_eq!(
            args.resolve_service_token().unwrap().as_deref(),
            Some("file-token")
        );

        // A group/other-readable file is rejected instead of being trusted.
        std::fs::set_permissions(&path, std::fs::Permissions::from_mode(0o640)).unwrap();
        let args = CliArgs::try_parse_from([
            "alhalte-banquette",
            "--room-id",
            "777",
            "--admin",
            "1",
            "--service-token-file",
            path.to_str().unwrap(),
        ])
        .unwrap();
        assert!(args.resolve_service_token().is_err());
    }
}
