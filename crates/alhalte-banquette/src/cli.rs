//! Command-line interface arguments for `alhalte-banquette`.

use std::path::PathBuf;

use clap::Parser;

/// Command-line arguments for the `alhalte-banquette` room daemon.
#[derive(Parser, Debug, Clone)]
#[command(
    name = "alhalte-banquette",
    about = "Session room process managing scenes, logs, and state relay for Alhalte",
    version
)]
pub struct CliArgs {
    /// 64-bit room identifier (16 hex characters or legacy decimal).
    #[arg(long, env = "ALHALTE_ROOM_ID", value_parser = parse_room_id_arg)]
    pub room_id: u64,

    /// Initial room administrator account ID.
    #[arg(long, alias = "owner", env = "ALHALTE_ADMIN_ACCOUNT")]
    pub admin: u64,

    /// UNIX domain socket path for communication with `alhalte-maitre-d`.
    #[arg(
        long,
        default_value = "/tmp/alhalte-banquette.sock",
        env = "ALHALTE_SOCKET_PATH"
    )]
    pub socket: PathBuf,

    /// Base HTTP URL of the `alhalte-cellar` content storage service.
    #[arg(
        long,
        default_value = "http://127.0.0.1:8080",
        env = "ALHALTE_CELLAR_URL"
    )]
    pub cellar_url: String,

    /// Log chunk size exponent $N$. One chunk holds $1 \ll N$ entries (default 8 = 256 entries).
    #[arg(
        short = 'n',
        long,
        default_value = "8",
        env = "ALHALTE_CHUNK_SIZE_EXPONENT"
    )]
    pub chunk_size_exponent: u8,

    /// Periodic heartbeat interval in seconds (default 240 seconds = 4 minutes).
    #[arg(long, default_value = "240", env = "ALHALTE_HEARTBEAT_INTERVAL_SECS")]
    pub heartbeat_interval_secs: u64,

    /// Persisted `RoomData` tin ID to restore instead of starting an empty room.
    ///
    /// `maitre-d` reads the room head before spawning and passes it here. When
    /// present, startup fails loudly if the tin cannot be downloaded, decoded,
    /// or validated against `--room-id`.
    #[arg(long, env = "ALHALTE_ROOM_TIN", value_parser = parse_tin_id_arg)]
    pub room_tin: Option<tin::TinId>,

    /// Internal cellar service token used for room state persistence.
    ///
    /// Sent as `X-Alhalte-Service-Token` so internal writes do not impersonate a
    /// user session. The value is never logged.
    #[arg(long, env = "ALHALTE_CELLAR_SERVICE_TOKEN", hide_env_values = true)]
    pub service_token: Option<String>,
}

/// Parses a 64-hex-character tin ID argument into a [`tin::TinId`].
fn parse_tin_id_arg(value: &str) -> Result<tin::TinId, String> {
    let value = value.trim();
    if value.len() != 64 || !value.bytes().all(|byte| byte.is_ascii_hexdigit()) {
        return Err("room tin ID must be 64 hexadecimal characters".to_string());
    }
    let mut out = [0u8; 32];
    hex::decode_to_slice(value, &mut out)
        .map_err(|_| "room tin ID must be 64 hexadecimal characters".to_string())?;
    Ok(out)
}

/// Parses a room ID argument in canonical 16-hex or legacy decimal form.
///
/// A 16-character all-digit string is interpreted as hex, matching the
/// canonical room ID form generated by the client.
fn parse_room_id_arg(value: &str) -> Result<u64, String> {
    let value = value.trim();
    if value.is_empty() {
        return Err("room ID must not be empty".to_string());
    }

    if value.len() == 16 && value.bytes().all(|byte| byte.is_ascii_hexdigit()) {
        return u64::from_str_radix(value, 16)
            .map_err(|_| "room ID is not a valid 16-hex value".to_string());
    }

    if value.bytes().all(|byte| byte.is_ascii_digit()) {
        return value
            .parse::<u64>()
            .map_err(|_| "room ID is not a valid decimal 64-bit unsigned integer".to_string());
    }

    Err(
        "room ID must be 16 hexadecimal characters or a decimal 64-bit unsigned integer"
            .to_string(),
    )
}

/// Parses CLI arguments from `std::env::args_os()`.
pub fn parse_cli_args() -> CliArgs {
    CliArgs::parse()
}

#[cfg(test)]
mod tests {
    use super::*;

    // spec: alhalte-banquette/cli --room-id canonical 16 hex + legacy decimal
    #[test]
    fn accepts_hex_and_decimal_room_ids() {
        let hex = CliArgs::try_parse_from([
            "alhalte-banquette",
            "--room-id",
            "abcdef0123456789",
            "--admin",
            "1",
        ])
        .unwrap();
        assert_eq!(hex.room_id, 0xabcdef0123456789);

        let decimal =
            CliArgs::try_parse_from(["alhalte-banquette", "--room-id", "777", "--admin", "1"])
                .unwrap();
        assert_eq!(decimal.room_id, 777);

        let padded = CliArgs::try_parse_from([
            "alhalte-banquette",
            "--room-id",
            "0000000000000309",
            "--admin",
            "1",
        ])
        .unwrap();
        assert_eq!(padded.room_id, 0x309);
    }

    #[test]
    fn rejects_arbitrary_room_ids() {
        assert!(
            CliArgs::try_parse_from(["alhalte-banquette", "--room-id", "room-1", "--admin", "1",])
                .is_err()
        );
        assert!(parse_room_id_arg("0x1234").is_err());
        assert!(parse_room_id_arg("18446744073709551616").is_err());
    }

    // spec: alhalte-banquette/persistence 0007 --room-tin restore argument
    #[test]
    fn parses_room_tin_and_service_token() {
        let tin_hex = "ab".repeat(32);
        let args = CliArgs::try_parse_from([
            "alhalte-banquette",
            "--room-id",
            "abcdef0123456789",
            "--admin",
            "1",
            "--room-tin",
            &tin_hex,
            "--service-token",
            "internal-secret",
        ])
        .unwrap();
        assert_eq!(args.room_tin, Some([0xabu8; 32]));
        assert_eq!(args.service_token.as_deref(), Some("internal-secret"));

        // No head means a new room.
        let args =
            CliArgs::try_parse_from(["alhalte-banquette", "--room-id", "777", "--admin", "1"])
                .unwrap();
        assert_eq!(args.room_tin, None);
        assert_eq!(args.service_token, None);

        // Tin IDs must be exactly 64 hex characters.
        assert!(
            CliArgs::try_parse_from([
                "alhalte-banquette",
                "--room-id",
                "777",
                "--admin",
                "1",
                "--room-tin",
                "abcd",
            ])
            .is_err()
        );
    }
}
