//! Canonical room identifiers shared by the HTTP / WebSocket routes.
//!
//! A room ID is a 64-bit unsigned integer. Its canonical textual form is 16
//! lowercase hexadecimal characters (the form produced by
//! `generateRoomUrl` in `web/alhalte-argenterie`). Legacy room URLs used a
//! decimal form, so decimal strings are still accepted when parsing; they are
//! normalized to the canonical 16-hex form by [`RoomId`]'s [`Display`]
//! implementation.
//!
//! Reference: `crates/alhalte-maitre-d/ARCHITECTURE.md` (room ID contract).

use std::fmt;
use std::str::FromStr;

use serde::{Deserialize, Serialize};

/// A parsed room identifier.
///
/// The wrapped value is the 64-bit numeric room ID. Parsing accepts either the
/// canonical 16-hex form or a legacy decimal `u64` string; [`Display`] always
/// emits the canonical 16-hex form.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash, Serialize, Deserialize)]
#[serde(try_from = "String", into = "String")]
pub struct RoomId(u64);

/// Error returned when a string is not a valid room identifier.
#[derive(Debug, Clone, Copy, PartialEq, Eq, thiserror::Error)]
#[error("room ID must be 16 hexadecimal characters or a decimal 64-bit unsigned integer")]
pub struct RoomIdParseError;

impl RoomId {
    /// Creates a room ID from its numeric representation.
    #[must_use]
    pub const fn new(value: u64) -> Self {
        Self(value)
    }

    /// Returns the numeric representation used by `alhalte-banquette`.
    #[must_use]
    pub const fn as_u64(self) -> u64 {
        self.0
    }
}

impl From<u64> for RoomId {
    fn from(value: u64) -> Self {
        Self(value)
    }
}

impl From<RoomId> for u64 {
    fn from(value: RoomId) -> Self {
        value.0
    }
}

impl From<RoomId> for String {
    fn from(value: RoomId) -> Self {
        value.to_string()
    }
}

impl fmt::Display for RoomId {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        // 16 lowercase hex characters; this is the canonical room ID form.
        write!(f, "{:016x}", self.0)
    }
}

impl FromStr for RoomId {
    type Err = RoomIdParseError;

    fn from_str(value: &str) -> Result<Self, Self::Err> {
        let value = value.trim();
        if value.is_empty() {
            return Err(RoomIdParseError);
        }

        // Canonical form first. A 16-character string consisting only of
        // decimal digits is interpreted as hex, because that is the form
        // generated by the client and emitted by `Display`.
        if value.len() == 16 && value.bytes().all(|byte| byte.is_ascii_hexdigit()) {
            return u64::from_str_radix(value, 16)
                .map(Self)
                .map_err(|_| RoomIdParseError);
        }

        // Legacy migration form: plain decimal `u64`.
        if value.bytes().all(|byte| byte.is_ascii_digit()) {
            return value.parse::<u64>().map(Self).map_err(|_| RoomIdParseError);
        }

        Err(RoomIdParseError)
    }
}

impl TryFrom<String> for RoomId {
    type Error = RoomIdParseError;

    fn try_from(value: String) -> Result<Self, Self::Error> {
        value.parse()
    }
}

/// Parses a room ID accepted by the HTTP / WebSocket routes.
///
/// This is a convenience wrapper around [`RoomId::from_str`] for call sites
/// that do not need the typed wrapper.
///
/// # Errors
///
/// Returns [`RoomIdParseError`] when `value` is neither 16 hex characters nor
/// a decimal `u64`.
pub fn parse_room_id(value: &str) -> Result<RoomId, RoomIdParseError> {
    value.parse()
}

#[cfg(test)]
mod tests {
    use super::*;

    // spec: alhalte-maitre-d/room-id canonical 16 hex + legacy decimal
    #[test]
    fn parses_canonical_hex_and_legacy_decimal() {
        let hex = "abcdef0123456789".parse::<RoomId>().unwrap();
        assert_eq!(hex.as_u64(), 0xabcdef0123456789);
        assert_eq!(hex.to_string(), "abcdef0123456789");

        let decimal = "777".parse::<RoomId>().unwrap();
        assert_eq!(decimal.as_u64(), 777);
        assert_eq!(decimal.to_string(), "0000000000000309");

        assert_eq!("0000000000000309".parse::<RoomId>().unwrap(), decimal);
        assert_eq!(
            "FFFFFFFFFFFFFFFF".parse::<RoomId>().unwrap().to_string(),
            "ffffffffffffffff"
        );
    }

    #[test]
    fn rejects_arbitrary_strings() {
        for invalid in ["", "room-1", "0x1234", "gggggggggggggggg"] {
            assert!(invalid.parse::<RoomId>().is_err(), "{invalid} should fail");
        }
        assert!("18446744073709551616".parse::<RoomId>().is_err());
    }
}
