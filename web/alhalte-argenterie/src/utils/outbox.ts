/**
 * Durable offline outbox for the Alhalte Argenterie web client.
 *
 * While the server is unreachable, messages and character edits are written to an
 * IndexedDB-backed queue instead of being dropped. Entries older than
 * {@link OUTBOX_TTL_MS} (30 days) are discarded lazily whenever the queue is read,
 * and {@link Outbox.flush} replays the survivors through a caller supplied handler,
 * deleting only the entries the handler accepted.
 *
 * The storage backend is injectable (see {@link OutboxStorage}): an IndexedDB
 * implementation and an in-memory implementation are provided. Environments
 * without `indexedDB` (jsdom, SSR, private browsing modes that disable it) fall
 * back to the memory implementation so the API never throws just because
 * persistence is unavailable. The memory fallback is intentionally lossy.
 *
 * References:
 * - ARCHITECTURE.md: `## alhalte-argenterie -> ### 発言とログ表示`
 * - ARCHITECTURE.md: `## alhalte-argenterie -> ### ローカル保存`
 * - GitHub Issue #109 / sub-issue #137: `オフラインメッセージ・キャラクターの永続キュー`
 */

/** Lifetime of an outbox entry: 30 days in milliseconds. */
export const OUTBOX_TTL_MS = 30 * 24 * 60 * 60 * 1000;

/** IndexedDB database name used by {@link IndexedDbOutboxStorage}. */
export const OUTBOX_DB_NAME = 'alhalte-argenterie-outbox';

/** IndexedDB object store name used by {@link IndexedDbOutboxStorage}. */
export const OUTBOX_STORE_NAME = 'outbox';

/** IndexedDB schema version used by {@link IndexedDbOutboxStorage}. */
export const OUTBOX_DB_VERSION = 1;

/** Primary key path of the outbox object store. */
export const OUTBOX_KEY_PATH = 'id';

/** Kinds of work that can be queued while offline. */
export type OutboxKind = 'message' | 'character' | 'state' | 'asset';

/** All supported {@link OutboxKind} values, in a stable order. */
export const OUTBOX_KINDS: readonly OutboxKind[] = ['message', 'character', 'state', 'asset'];

/**
 * A single durable outbox entry.
 *
 * `payload` is opaque to the outbox and is persisted as-is (IndexedDB performs a
 * structured clone); callers own its shape and its versioning.
 */
export interface OutboxEntry {
  /** Unique entry id (a UUID when generated by {@link Outbox.enqueue}). */
  readonly id: string;
  /** Room the work belongs to. */
  readonly roomId: string;
  /** Kind of work, used for filtering and for the queue notice copy. */
  readonly kind: OutboxKind;
  /** Epoch milliseconds at which the entry was queued. */
  readonly createdAt: number;
  /** Serializable payload to hand to the reconnect handler. */
  readonly payload: unknown;
}

/**
 * Input accepted by {@link Outbox.enqueue}.
 *
 * `id` and `createdAt` are optional so callers that already have them (for
 * example when replaying a pending entry) can preserve them; otherwise they are
 * generated from the clock and `crypto.randomUUID`.
 */
export interface OutboxEntryInput {
  /** Room the work belongs to. */
  readonly roomId: string;
  /** Kind of work. Must be one of {@link OUTBOX_KINDS}. */
  readonly kind: OutboxKind;
  /** Serializable payload. */
  readonly payload: unknown;
  /** Optional caller supplied id. */
  readonly id?: string;
  /** Optional caller supplied creation time in epoch milliseconds. */
  readonly createdAt?: number;
}

/** Backend a concrete {@link OutboxStorage} is built on. */
export type OutboxStorageKind = 'indexeddb' | 'memory';

/**
 * Injectable persistence backend for {@link Outbox}.
 *
 * Implementations must be safe to call concurrently: two tabs writing at the
 * same time must not lose entries. Entries are addressed by {@link OutboxEntry.id},
 * so {@link OutboxStorage.put} is an upsert.
 */
export interface OutboxStorage {
  /** Backend identifier, useful for diagnostics and tests. */
  readonly kind: OutboxStorageKind;
  /** Read every stored entry. Ordering is not significant. */
  getAll(): Promise<OutboxEntry[]>;
  /** Insert or replace one entry by its id. */
  put(entry: OutboxEntry): Promise<void>;
  /** Delete one entry by id. Deleting a missing id is a no-op. */
  delete(id: string): Promise<void>;
  /** Delete several entries in one atomic batch. */
  deleteMany(ids: readonly string[]): Promise<void>;
  /** Delete every entry. */
  clear(): Promise<void>;
  /** Release the underlying connection, if any. */
  close(): void;
}

/** Counts returned by {@link Outbox.flush}. */
export interface FlushResult {
  /** Number of non-expired entries offered to the handler. */
  attempted: number;
  /** Number of entries the handler accepted and that were deleted. */
  succeeded: number;
  /** Number of entries the handler rejected or that threw; they stay queued. */
  failed: number;
  /** Number of expired entries pruned before flushing; never offered to the handler. */
  expired: number;
}

/**
 * Replay callback used by {@link Outbox.flush}.
 *
 * Resolve normally (or return `true`) to mark the entry as delivered. Throw or
 * return `false` to keep the entry queued for the next attempt.
 */
export type OutboxFlushHandler = (
  entry: OutboxEntry,
) => boolean | void | Promise<boolean | void>;

/** Options for {@link Outbox}. */
export interface OutboxOptions {
  /** Custom storage backend. Defaults to IndexedDB, or memory when unavailable. */
  readonly storage?: OutboxStorage;
  /** Clock injection, in epoch milliseconds. Defaults to {@link Date.now}. */
  readonly now?: () => number;
}

/**
 * Returns true when the given kind is a supported {@link OutboxKind}.
 */
export function isOutboxKind(value: unknown): value is OutboxKind {
  return typeof value === 'string' && (OUTBOX_KINDS as readonly string[]).includes(value);
}

/**
 * Returns true when a usable IndexedDB factory is exposed on `globalThis`.
 *
 * This is a synchronous capability check; it does not prove that opening the
 * database will succeed. jsdom and Node do not provide IndexedDB, so this
 * returns false there and {@link createDefaultOutboxStorage} picks the memory
 * backend.
 */
export function isIndexedDbAvailable(): boolean {
  const candidate = (globalThis as { indexedDB?: IDBFactory | null }).indexedDB;
  return candidate !== undefined && candidate !== null;
}

/**
 * Lazily created id factory: `crypto.randomUUID` when available, otherwise a
 * time + random suffix that is unique enough for a single browser profile.
 */
function createId(): string {
  const cryptoApi = (globalThis as { crypto?: Crypto }).crypto;
  if (cryptoApi && typeof cryptoApi.randomUUID === 'function') {
    return cryptoApi.randomUUID();
  }
  const random = Math.random().toString(36).slice(2, 10);
  return `outbox-${Date.now().toString(36)}-${random}`;
}

/** Ascending `createdAt` order, with the id as a deterministic tie-breaker. */
function compareEntries(a: OutboxEntry, b: OutboxEntry): number {
  if (a.createdAt !== b.createdAt) return a.createdAt - b.createdAt;
  return a.id < b.id ? -1 : a.id > b.id ? 1 : 0;
}

/** Validates an entry input and throws a `TypeError` when it is malformed. */
function assertEntryInput(input: OutboxEntryInput): void {
  if (typeof input !== 'object' || input === null) {
    throw new TypeError('outbox: entry must be an object');
  }
  if (typeof input.roomId !== 'string' || input.roomId.length === 0) {
    throw new TypeError('outbox: entry.roomId must be a non-empty string');
  }
  if (!isOutboxKind(input.kind)) {
    throw new TypeError(
      `outbox: entry.kind must be one of ${OUTBOX_KINDS.join(', ')} (got ${String(input.kind)})`,
    );
  }
  if (input.id !== undefined && (typeof input.id !== 'string' || input.id.length === 0)) {
    throw new TypeError('outbox: entry.id must be a non-empty string when provided');
  }
  if (
    input.createdAt !== undefined &&
    (typeof input.createdAt !== 'number' || !Number.isFinite(input.createdAt))
  ) {
    throw new TypeError('outbox: entry.createdAt must be a finite number when provided');
  }
}

/**
 * In-memory {@link OutboxStorage}.
 *
 * Used as the jsdom/SSR fallback and as a test double. Entries live for the
 * lifetime of the instance and are lost on reload, by design.
 */
export class MemoryOutboxStorage implements OutboxStorage {
  /** @inheritdoc */
  readonly kind: OutboxStorageKind = 'memory';

  private readonly entries = new Map<string, OutboxEntry>();

  /** @inheritdoc */
  async getAll(): Promise<OutboxEntry[]> {
    return [...this.entries.values()].map((entry) => ({ ...entry }));
  }

  /** @inheritdoc */
  async put(entry: OutboxEntry): Promise<void> {
    this.entries.set(entry.id, { ...entry });
  }

  /** @inheritdoc */
  async delete(id: string): Promise<void> {
    this.entries.delete(id);
  }

  /** @inheritdoc */
  async deleteMany(ids: readonly string[]): Promise<void> {
    for (const id of ids) this.entries.delete(id);
  }

  /** @inheritdoc */
  async clear(): Promise<void> {
    this.entries.clear();
  }

  /** @inheritdoc */
  close(): void {
    // Nothing to release.
  }
}

/**
 * IndexedDB {@link OutboxStorage}.
 *
 * The database and object store are created on first use. Every mutation runs in
 * its own transaction, so concurrent writers in other tabs cannot interleave
 * partial batches. The connection is reused until {@link close} is called or the
 * browser requests a version change (another tab upgrading the schema), in which
 * case the connection is dropped and reopened on the next call.
 */
export class IndexedDbOutboxStorage implements OutboxStorage {
  /** @inheritdoc */
  readonly kind: OutboxStorageKind = 'indexeddb';

  private readonly factory: IDBFactory;
  private readonly dbName: string;
  private dbPromise: Promise<IDBDatabase> | null = null;

  /**
   * @param factory IndexedDB factory to use. Defaults to `globalThis.indexedDB`.
   * @param dbName Database name. Override in tests to isolate databases.
   */
  constructor(factory: IDBFactory = requireIndexedDbFactory(), dbName: string = OUTBOX_DB_NAME) {
    this.factory = factory;
    this.dbName = dbName;
  }

  /**
   * Opens (and upgrades when needed) the outbox database, memoizing the
   * connection. A failed open is not memoized, so callers can retry.
   */
  private open(): Promise<IDBDatabase> {
    if (!this.dbPromise) {
      const promise = new Promise<IDBDatabase>((resolve, reject) => {
        let request: IDBOpenDBRequest;
        try {
          request = this.factory.open(this.dbName, OUTBOX_DB_VERSION);
        } catch (error) {
          reject(error);
          return;
        }
        request.onupgradeneeded = () => {
          const db = request.result;
          if (!db.objectStoreNames.contains(OUTBOX_STORE_NAME)) {
            const store = db.createObjectStore(OUTBOX_STORE_NAME, { keyPath: OUTBOX_KEY_PATH });
            store.createIndex('roomId', 'roomId', { unique: false });
            store.createIndex('createdAt', 'createdAt', { unique: false });
          }
        };
        request.onsuccess = () => {
          const db = request.result;
          db.onversionchange = () => {
            db.close();
            this.dbPromise = null;
          };
          resolve(db);
        };
        request.onerror = () => {
          reject(request.error ?? new Error(`outbox: failed to open database "${this.dbName}"`));
        };
        request.onblocked = () => {
          // Wait for the other connection to close; onsuccess still fires then.
        };
      });
      this.dbPromise = promise.catch((error: unknown) => {
        this.dbPromise = null;
        throw error;
      });
    }
    return this.dbPromise;
  }

  /**
   * Runs `action` inside one transaction and waits for it to commit.
   *
   * Request promises reject on request failure; the transaction is aborted and
   * the error is rethrown so callers never observe a partially applied batch.
   */
  private async withStore<T>(
    mode: IDBTransactionMode,
    action: (store: IDBObjectStore) => Promise<T> | T,
  ): Promise<T> {
    const db = await this.open();
    const tx = db.transaction(OUTBOX_STORE_NAME, mode);
    const store = tx.objectStore(OUTBOX_STORE_NAME);
    const done = new Promise<void>((resolve, reject) => {
      tx.oncomplete = () => resolve();
      tx.onerror = () => reject(tx.error ?? new Error('outbox: IndexedDB transaction failed'));
      tx.onabort = () => reject(tx.error ?? new Error('outbox: IndexedDB transaction aborted'));
    });
    // If the action throws first, `done` may reject unobserved; keep it handled.
    done.catch(() => {});
    let result: T;
    try {
      result = await action(store);
    } catch (error) {
      try {
        tx.abort();
      } catch {
        // Transaction already finished; nothing to abort.
      }
      throw error;
    }
    await done;
    return result;
  }

  /** @inheritdoc */
  async getAll(): Promise<OutboxEntry[]> {
    return this.withStore('readonly', (store) =>
      requestResult<OutboxEntry[]>(store.getAll()),
    );
  }

  /** @inheritdoc */
  async put(entry: OutboxEntry): Promise<void> {
    await this.withStore('readwrite', (store) =>
      requestResult(store.put({ ...entry })),
    );
  }

  /** @inheritdoc */
  async delete(id: string): Promise<void> {
    await this.withStore('readwrite', (store) => requestResult(store.delete(id)));
  }

  /** @inheritdoc */
  async deleteMany(ids: readonly string[]): Promise<void> {
    if (ids.length === 0) return;
    await this.withStore('readwrite', (store) =>
      Promise.all(ids.map((id) => requestResult(store.delete(id)))),
    );
  }

  /** @inheritdoc */
  async clear(): Promise<void> {
    await this.withStore('readwrite', (store) => requestResult(store.clear()));
  }

  /** @inheritdoc */
  close(): void {
    const pending = this.dbPromise;
    this.dbPromise = null;
    if (pending) {
      void pending.then(
        (db) => db.close(),
        () => {},
      );
    }
  }
}

/** Wraps an IndexedDB request in a promise that settles on success or error. */
function requestResult<T>(request: IDBRequest<T>): Promise<T> {
  return new Promise<T>((resolve, reject) => {
    request.onsuccess = () => resolve(request.result);
    request.onerror = () => reject(request.error ?? new Error('outbox: IndexedDB request failed'));
  });
}

/** Returns `globalThis.indexedDB`, throwing a descriptive error when missing. */
function requireIndexedDbFactory(): IDBFactory {
  const factory = (globalThis as { indexedDB?: IDBFactory }).indexedDB;
  if (!factory) {
    throw new Error(
      'outbox: indexedDB is not available in this environment; use MemoryOutboxStorage or Outbox\'s default storage',
    );
  }
  return factory;
}

/**
 * Creates the best available storage backend.
 *
 * Returns {@link IndexedDbOutboxStorage} when `indexedDB` exists and
 * {@link MemoryOutboxStorage} otherwise (jsdom, SSR, privacy-restricted
 * browsers). The choice is synchronous; a database that exists but fails to
 * open surfaces the error on the first operation rather than silently dropping
 * data.
 */
export function createDefaultOutboxStorage(): OutboxStorage {
  return isIndexedDbAvailable() ? new IndexedDbOutboxStorage() : new MemoryOutboxStorage();
}

/**
 * Durable offline outbox.
 *
 * Typical use:
 *
 * ```ts
 * const outbox = getOutbox();
 * await outbox.enqueue({ roomId, kind: 'message', payload: record });
 * const entries = await outbox.list(roomId, 'message');
 * await outbox.flush(roomId, async (entry) => socket.appendLog(entry.payload));
 * ```
 *
 * Reads (`list`, `flush`, `pruneExpired`) drop entries older than
 * {@link OUTBOX_TTL_MS} and report how many were dropped through their return
 * value and {@link lastPrunedCount}; expired entries are never handed to the
 * flush handler.
 */
export class Outbox {
  private readonly storage: OutboxStorage;
  private readonly now: () => number;
  private prunedCount = 0;

  /**
   * @param options Optional storage backend and clock injection.
   */
  constructor(options: OutboxOptions = {}) {
    this.storage = options.storage ?? createDefaultOutboxStorage();
    this.now = options.now ?? Date.now;
  }

  /** Backend identifier of the storage in use. */
  get storageKind(): OutboxStorageKind {
    return this.storage.kind;
  }

  /** True when persistence fell back to memory (entries will not survive reload). */
  get usingMemoryFallback(): boolean {
    return this.storage.kind === 'memory';
  }

  /** Number of entries pruned by the most recent read. */
  get lastPrunedCount(): number {
    return this.prunedCount;
  }

  /** Releases the underlying storage connection. The outbox must not be reused afterwards. */
  close(): void {
    this.storage.close();
  }

  /**
   * Queues one entry.
   *
   * A missing `id` is generated and a missing `createdAt` is taken from the
   * injected clock. The stored entry (including generated fields) is returned.
   *
   * @throws {TypeError} When `roomId` is empty, `kind` is unknown, or supplied
   * `id` / `createdAt` values are invalid.
   */
  async enqueue(input: OutboxEntryInput): Promise<OutboxEntry> {
    assertEntryInput(input);
    const entry: OutboxEntry = {
      id: input.id ?? createId(),
      roomId: input.roomId,
      kind: input.kind,
      createdAt: input.createdAt ?? this.now(),
      payload: input.payload,
    };
    await this.storage.put(entry);
    return entry;
  }

  /**
   * Lists entries for a room in ascending `createdAt` order.
   *
   * Expired entries are pruned as a side effect; see {@link lastPrunedCount}.
   *
   * @param roomId Room to list.
   * @param kind Optional kind filter.
   */
  async list(roomId: string, kind?: OutboxKind): Promise<OutboxEntry[]> {
    await this.pruneExpired();
    const all = await this.storage.getAll();
    return all
      .filter((entry) => entry.roomId === roomId && (kind === undefined || entry.kind === kind))
      .sort(compareEntries)
      .map((entry) => ({ ...entry }));
  }

  /**
   * Removes one entry by id. Unknown ids are ignored.
   */
  async remove(id: string): Promise<void> {
    await this.storage.delete(id);
  }

  /**
   * Clears the queue.
   *
   * @param roomId When provided, only that room's entries are removed.
   */
  async clear(roomId?: string): Promise<void> {
    if (roomId === undefined) {
      await this.storage.clear();
      return;
    }
    const all = await this.storage.getAll();
    const ids = all.filter((entry) => entry.roomId === roomId).map((entry) => entry.id);
    await this.storage.deleteMany(ids);
  }

  /**
   * Prunes entries older than {@link OUTBOX_TTL_MS}.
   *
   * An entry is expired when `now - createdAt > OUTBOX_TTL_MS`; an entry exactly
   * on the boundary is kept.
   *
   * @param now Reference time in epoch milliseconds. Defaults to the injected clock.
   * @returns Number of entries removed.
   */
  async pruneExpired(now: number = this.now()): Promise<number> {
    const cutoff = now - OUTBOX_TTL_MS;
    const all = await this.storage.getAll();
    const expiredIds = all
      .filter((entry) => entry.createdAt < cutoff)
      .map((entry) => entry.id);
    if (expiredIds.length > 0) {
      await this.storage.deleteMany(expiredIds);
    }
    this.prunedCount = expiredIds.length;
    return expiredIds.length;
  }

  /**
   * Replays a room's queue through `handler`, deleting only the entries the
   * handler accepted (resolved without returning `false`).
   *
   * Entries are offered sequentially in ascending `createdAt` order so that
   * ordered work (messages, character edits) reaches the server in order. A
   * handler rejection or throw leaves that entry queued and continues with the
   * next one. Expired entries are pruned first and are never offered.
   *
   * @param roomId Room whose entries should be flushed.
   * @param handler Replay callback, invoked once per pending entry.
   * @returns Counts describing the attempt; see {@link FlushResult}.
   */
  async flush(roomId: string, handler: OutboxFlushHandler): Promise<FlushResult> {
    const now = this.now();
    const cutoff = now - OUTBOX_TTL_MS;
    const all = await this.storage.getAll();
    const expiredIds = all
      .filter((entry) => entry.createdAt < cutoff)
      .map((entry) => entry.id);
    if (expiredIds.length > 0) {
      await this.storage.deleteMany(expiredIds);
    }
    this.prunedCount = expiredIds.length;

    const pending = all
      .filter((entry) => entry.roomId === roomId && entry.createdAt >= cutoff)
      .sort(compareEntries);

    const deliveredIds: string[] = [];
    let failed = 0;
    for (const entry of pending) {
      try {
        const accepted = await handler({ ...entry });
        if (accepted === false) {
          failed += 1;
        } else {
          deliveredIds.push(entry.id);
        }
      } catch {
        failed += 1;
      }
    }
    if (deliveredIds.length > 0) {
      await this.storage.deleteMany(deliveredIds);
    }

    return {
      attempted: pending.length,
      succeeded: deliveredIds.length,
      failed,
      expired: expiredIds.length,
    };
  }
}

let defaultOutbox: Outbox | null = null;

/**
 * Returns the process-wide {@link Outbox} singleton.
 *
 * The singleton is created lazily so importing this module never touches
 * IndexedDB. In jsdom (no `indexedDB`) it transparently uses memory storage.
 */
export function getOutbox(): Outbox {
  if (!defaultOutbox) {
    defaultOutbox = new Outbox();
  }
  return defaultOutbox;
}

/**
 * Creates an independent {@link Outbox} with an injected storage backend.
 *
 * Prefer this in tests and in features that want their own clock or storage.
 */
export function createOutbox(options: OutboxOptions = {}): Outbox {
  return new Outbox(options);
}

/**
 * Disposes the singleton returned by {@link getOutbox} and closes its storage.
 *
 * Intended for tests and to recover from a broken storage backend. The next
 * {@link getOutbox} call builds a fresh instance.
 */
export function resetOutbox(): void {
  if (!defaultOutbox) return;
  defaultOutbox.close();
  defaultOutbox = null;
}
