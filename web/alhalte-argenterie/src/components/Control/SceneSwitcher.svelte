<script lang="ts">
  /**
   * Reusable scene search / switcher (Issue #269).
   *
   * The control panel header and the 「キャラクターを移動」 modal share this one
   * component so a scene is resolved the same way everywhere: an M3 Search over
   * the room's scenes, Enter resolving the typed name, and — for an admin — the
   * option to create the scene on the spot.
   *
   * Resolution order (`resolve()`, used by Enter and by the modal's 「移動」
   * button):
   *
   * 1. an exact name match (case-insensitive, trimmed) selects that scene,
   * 2. otherwise the first filtered candidate is selected,
   * 3. otherwise, when `canCreate`, a scene is created for the typed name with
   *    an id generated by `generateSceneId()`,
   * 4. otherwise nothing happens (a non-admin gets no create affordance).
   *
   * The component owns the query, the pending spinner and the failure text; it
   * never mutates the scene list. A callback that returns `false` (or throws)
   * is reported as 「サーバーと通信できませんでした」 in
   * `<testIdPrefix>-error`; the parent keeps the authoritative state.
   *
   * References:
   * - ARCHITECTURE.md: `## alhalte-argenterie -> ### scene の管理操作`
   * - ARCHITECTURE.md: `## alhalte-argenterie -> ### キャラクター同期`
   * - GitHub Issue #269: シーンの移動からシーンを新規作成する導線を作る
   */
  import { CircularProgress, Item, Search } from 'noph-ui';
  import { Icon } from 'noph-ui/icons';
  import type { Scene } from '../../types/index.js';
  import { generateSceneId } from '../../utils/sceneSettings.js';

  /** Failure text shared with `App` / the scene management controls. */
  const SCENE_SWITCHER_ERROR_MESSAGE = 'サーバーと通信できませんでした';

  let {
    scenes = [],
    currentSceneId = null,
    canCreate = false,
    testIdPrefix = 'scene-search',
    /**
     * Test id of the empty-result notice. Kept as a prop because the header has
     * carried `empty-search-notice` since Issue #89 and two switchers can be
     * mounted at once (header + move modal).
     */
    emptyNoticeTestId = null,
    placeholder = 'シーンを検索',
    ariaLabel = 'シーンを検索・切り替え',
    searchClass = undefined,
    onSelectScene,
    onCreateScene,
  }: {
    /** Every scene of the room, in the order the server lists them. */
    scenes?: Scene[];
    /** Scene id rendered as the selected row (`null` = nothing selected). */
    currentSceneId?: string | null;
    /**
     * Whether Enter may create a scene for an unknown name. Admin-only: scene
     * creation is rejected by banquette for every other role.
     */
    canCreate?: boolean;
    /** Prefix of every `data-testid` this component renders. */
    testIdPrefix?: string;
    /** Overrides `<testIdPrefix>-empty-notice`. */
    emptyNoticeTestId?: string | null;
    placeholder?: string;
    ariaLabel?: string;
    /** Extra class applied to the underlying `Search` (layout of the host). */
    searchClass?: string;
    /** Selects an existing scene; `false` reports a failure (no local change). */
    onSelectScene?: (sceneId: string) => void | boolean | Promise<void | boolean>;
    /**
     * Creates the scene `sceneId` with the typed `name`; `false` reports a
     * failure. Only called when `canCreate`.
     */
    onCreateScene?: (
      name: string,
      sceneId: string,
    ) => void | boolean | Promise<void | boolean>;
  } = $props();

  let query = $state('');
  let isSearchExpanded = $state(false);
  /** A select / create round trip is waiting for its acknowledgement. */
  let isPending = $state(false);
  /** Failure text of the last attempt (`null` while healthy). */
  let errorMessage = $state<string | null>(null);

  let resolvedEmptyNoticeId = $derived(emptyNoticeTestId ?? `${testIdPrefix}-empty-notice`);
  let trimmedQuery = $derived(query.trim());

  let filteredScenes = $derived.by(() => {
    const q = trimmedQuery.toLowerCase();
    if (!q) return scenes;
    return scenes.filter((scene) => (scene.name ?? '').toLowerCase().includes(q));
  });

  /** The scene whose name equals the query exactly (trimmed, case-insensitive). */
  let exactMatch = $derived.by(() => {
    const q = trimmedQuery.toLowerCase();
    if (!q) return null;
    return scenes.find((scene) => (scene.name ?? '').trim().toLowerCase() === q) ?? null;
  });

  function closeResults(): void {
    isSearchExpanded = false;
    query = '';
  }

  /**
   * Runs one select / create round trip.
   *
   * `pending` serializes the attempts of this instance, so a double Enter or an
   * Enter followed by the 「移動」 button cannot send two overlapping actions.
   */
  async function run(
    action: () => void | boolean | Promise<void | boolean>,
  ): Promise<boolean> {
    if (isPending) return false;
    isPending = true;
    errorMessage = null;
    try {
      const result = await action();
      if (result === false) {
        errorMessage = SCENE_SWITCHER_ERROR_MESSAGE;
        return false;
      }
      closeResults();
      return true;
    } catch (error) {
      console.warn('[SceneSwitcher] Scene action failed:', error);
      errorMessage = SCENE_SWITCHER_ERROR_MESSAGE;
      return false;
    } finally {
      isPending = false;
    }
  }

  /** Selects an existing scene (item click / exact name / first candidate). */
  function selectScene(sceneId: string): Promise<boolean> {
    return run(() => onSelectScene?.(sceneId));
  }

  /**
   * Creates a scene for `name` with a freshly generated id.
   *
   * The id is generated here (not by the parent) so the header create and the
   * move modal's create-then-move path address the same scene without the
   * parent having to guess it.
   */
  function createScene(name: string): Promise<boolean> {
    const trimmed = name.trim();
    if (!trimmed) return Promise.resolve(false);
    return run(() => onCreateScene?.(trimmed, generateSceneId()));
  }

  /**
   * Resolves the typed name (Enter, and the move modal's 「移動」 button).
   *
   * Returns `true` when an action succeeded, `false` when it failed or when
   * there was nothing to do (empty query / no candidate and no create right).
   * Everything the component changes is local: the scene list and the current
   * scene belong to the parent.
   */
  export async function resolve(): Promise<boolean> {
    if (isPending) return false;
    const q = trimmedQuery;
    if (!q) return false;
    if (exactMatch) return selectScene(exactMatch.id);
    const first = filteredScenes[0];
    if (first) return selectScene(first.id);
    if (!canCreate) return false;
    return createScene(q);
  }

  function handleItemClick(sceneId: string): void {
    void selectScene(sceneId);
  }

  function handleCreateClick(): void {
    void createScene(query);
  }
</script>

<div class="scene-switcher" data-testid="{testIdPrefix}-root">
  <Search
    variant="contained"
    view="docked"
    {placeholder}
    bind:value={query}
    bind:expanded={isSearchExpanded}
    class={searchClass}
    inputAttributes={{
      'data-testid': `${testIdPrefix}-input`,
      'aria-label': ariaLabel,
    }}
    resultsAttributes={{
      'data-testid': `${testIdPrefix}-menu`,
      class: 'scene-switcher-results',
    }}
    onsearch={() => {
      void resolve();
    }}
  >
    {#each filteredScenes as scene (scene.id)}
      <Item
        type="button"
        role="option"
        selected={scene.id === currentSceneId}
        onclick={() => handleItemClick(scene.id)}
        data-testid="{testIdPrefix}-item-{scene.id}"
      >
        {#snippet start()}
          <Icon>{scene.id === currentSceneId ? 'check' : 'account_tree'}</Icon>
        {/snippet}
        {scene.name}
      </Item>
    {/each}

    {#if filteredScenes.length === 0}
      <!-- Admin: the name becomes a new scene. Everyone else keeps the plain
           "no such scene" notice (Issue #269). -->
      <div class="scene-switcher-empty-notice" data-testid={resolvedEmptyNoticeId}>
        {canCreate ? 'シーンは新規作成されます' : '該当するシーンがありません'}
      </div>
    {/if}

    {#if canCreate && trimmedQuery && !exactMatch}
      <!-- Explicit create affordance: Enter picks the first candidate, so a
           same-prefix name is only reachable by clicking this row. -->
      <Item
        type="button"
        role="option"
        onclick={handleCreateClick}
        data-testid="{testIdPrefix}-create-item"
      >
        {#snippet start()}<Icon>add</Icon>{/snippet}
        「{trimmedQuery}」を新規作成
      </Item>
    {/if}

    {#if isPending}
      <div class="scene-switcher-pending" role="status" data-testid="{testIdPrefix}-pending">
        <CircularProgress
          indeterminate
          wavy
          track={false}
          class="scene-switcher-progress"
          aria-label="送信中"
        />
        <span>処理中…</span>
      </div>
    {/if}
  </Search>

  {#if errorMessage}
    <p class="scene-switcher-error" role="alert" data-testid="{testIdPrefix}-error">
      {errorMessage}
    </p>
  {/if}
</div>

